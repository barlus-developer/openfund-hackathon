import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
mkdirSync("app/src/web3/generated", { recursive: true });
for (const name of ["OFLToken", "OpenFund"]) {
  const artifact = JSON.parse(
    readFileSync(`contracts/out/${name}.sol/${name}.json`, "utf8"),
  );
  writeFileSync(
    `app/src/web3/generated/${name}.ts`,
    `// Generated by scripts/sync-abis.mjs from Foundry. Do not edit.\nexport const ${name === "OFLToken" ? "tokenAbi" : "openFundAbi"} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
}
writeFileSync(
  "app/src/web3/generated/deployments.json",
  readFileSync("deployments/official.json"),
);
